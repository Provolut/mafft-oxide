pub fn blosum_mtx(
    n: i32,
    matrix: &mut [[f64; 20]; 20],
    freq: &mut [f64; 20],
    amino: &mut [u8; 26],
    amino_grp: &mut [i32; 0x100],
) {
    // `BLOSUMmtx()`'s dispatch. `n == -1` (`--aamatrix`) reads a user file and
    // can also override the frequencies and `rescale`; it is refused upstream.
    let tmpmtx: &[f64] = match n {
        30 => &TMPMTX30,
        45 => &TMPMTX45,
        50 => &TMPMTX50,
        62 => &TMPMTX62,
        80 => &TMPMTX80,
        90 => &TMPMTX90,
        100 => &TMPMTX100,
        _ => {
            eprintln!("blosum {} ?", n);
            std::process::exit(1);
        }
    };

    let mut count = 0usize;
    for i in 0..20 {
        for j in 0..=i {
            let v = tmpmtx[count];
            count += 1;
            matrix[i][j] = v;
            matrix[j][i] = v;
        }
    }
    freq.copy_from_slice(&FREQD);

    for i in 0..26 {
        amino[i] = LOCAMINOD[i];
    }
    for i in 0..26 {
        amino_grp[amino[i] as usize] = LOCGRPD[i];
    }
}
